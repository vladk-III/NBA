#!/usr/bin/env python3
"""Build the single-code-block versions of the NBA dashboard:

  model/nba_dashboard_colab.py   everything in one file: paste it into one Colab cell, or %run it
  model/NBA_Dashboard.ipynb      the same code as ONE notebook cell (plus a title cell)

Like the NFL dashboard, the one block holds the theme, dashboard, model training, predictions and
historical charts. The modular .py files stay the source of truth; re-run this after changing them:

    python model/build_colab.py
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT_PY = HERE / "nba_dashboard_colab.py"
OUT_NB = HERE / "NBA_Dashboard.ipynb"
INSERT_BEFORE = "def _load_model_modules():"

BANNER = '''# =============================================================================
# {title}
# =============================================================================
'''


def _body(name: str) -> str:
    src = (HERE / name).read_text()
    return src.replace("from __future__ import annotations\n", "").strip() + "\n"


def single_file() -> str:
    """Dashboard header (config, installs, imports), then core and models, then the rest of the
    dashboard. The dashboard sees BPSFilter and model_a in its own namespace and uses them directly."""
    dash = _body("nba_dashboard.py")
    head, sep, tail = dash.partition(INSERT_BEFORE)
    if not sep:
        raise RuntimeError(f"Marker {INSERT_BEFORE!r} not found in nba_dashboard.py")
    header = ("# Generated by model/build_colab.py from model/nba_model_core.py, model/nba_models.py and\n"
              "# model/nba_dashboard.py. Edit those files and rebuild instead of editing this one.\n\n")
    return (header + head.rstrip() + "\n\n\n"
            + BANNER.format(title="CORE — features, Bayesian Predictive Synthesis, odds, EV and grading")
            + _body("nba_model_core.py") + "\n\n"
            + BANNER.format(title="MODELS A, B, C — each forecasts the total and the home margin")
            + _body("nba_models.py") + "\n\n"
            + BANNER.format(title="DASHBOARD — data, pipelines, theme and UI")
            + sep + tail)


def notebook(code: str) -> str:
    title = """# 🏀 NBA Projections & Insight Ledger

Three models, each forecasting **both** the total and the home margin, blended by Bayesian Predictive Synthesis,
with Brier skill, confusion matrices and the Money Ball bet rules (expected value or credible interval). Data comes
from the [vladk-III/NBA](https://github.com/vladk-III/NBA) repo, which GitHub Actions updates every day.

**Run the cell below.** It installs what it needs and opens the dashboard. Daily: **1 Train → 2 Optimize BPS →
3 Predict**. Model state and `predictions_history.csv` are saved to Google Drive under `Stonks/Basketball/NBA/2026-27`.

*Generated by `model/build_colab.py`; edit the module files and rebuild rather than editing this notebook.*
"""
    nb = {"cells": [{"cell_type": "markdown", "metadata": {}, "source": title.splitlines(keepends=True)},
                    {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
                     "source": code.splitlines(keepends=True)}],
          "metadata": {"colab": {"provenance": []}, "kernelspec": {"display_name": "Python 3", "name": "python3"},
                       "language_info": {"name": "python"}},
          "nbformat": 4, "nbformat_minor": 0}
    return json.dumps(nb, indent=1, ensure_ascii=False) + "\n"


def build(write: bool = True) -> tuple[str, str]:
    code = single_file()
    nb = notebook(code)
    if write:
        OUT_PY.write_text(code)
        OUT_NB.write_text(nb)
    return code, nb


if __name__ == "__main__":
    code, _ = build()
    print(f"Wrote {OUT_PY} and {OUT_NB} ({len(code.splitlines())} lines, one code block)")
